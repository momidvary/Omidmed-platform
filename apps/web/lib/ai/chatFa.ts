import type { PatientCase } from "@/lib/types";
import { bodyRegionsFa } from "@/lib/data/bodyRegionsFa";

/* Persian versions of the template assistant prompts and replies. */
export const suggestedPromptsFa = [
  "تشخیص‌های افتراقی این بیمار را بر اساس یافته‌های ساختاریافته ثبت‌شده رتبه‌بندی کن، توضیح بده چه چیزی هر فرضیه را تأیید یا رد می‌کند و کدام تست‌ها بهتر آن‌ها را از هم جدا می‌کنند.",
  "برای این بیمار چه تست‌هایی انجام دهم؟",
  "یک برنامه درمانی برای آرتروز زانو بده.",
  "بعد از تعویض مفصل زانو (TKA) چه تمرین‌هایی ایمن است؟",
  "چطور برنامه این بیمار را پیشرفت دهم؟",
  "پرچم‌های قرمز کمردرد چیست؟",
];

export function buildChatReplyFa(question: string, caseContext?: PatientCase): string {
  // Persian text often joins suffixes with a zero-width non-joiner.
  const q = question.toLowerCase().replace(/\u200c/g, " ");
  const region = caseContext?.region ? bodyRegionsFa[caseContext.region] : undefined;
  const ctx = caseContext
    ? `با توجه به ${caseContext.name || "این بیمار"} (${region?.label ?? "ناحیه نامشخص"}، درد ${caseContext.painIntensity} از ۱۰): `
    : "";

  if (/red flag|پرچم( های?)? قرمز|علائم خطر/.test(q)) {
    return `${ctx}پرچم‌های قرمز کلیدی در کمردرد: بی‌حسی ناحیه زین‌اسبی، اختلال کنترل ادرار یا مدفوع، نقص عصبی پیشرونده، تروما قابل‌توجه، نشانه‌های بدخیمی (سابقه سرطان، کاهش وزن بی‌دلیل، درد شبانه دائمی) و نشانه‌های عفونت (تب). در صورت وجود هر کدام، برای ارزیابی پزشکی فوری ارجاع دهید. این فقط پشتیبان تصمیم‌گیری است — بالینی تأیید کنید.`;
  }
  if (/test|تست|معاینه/.test(q)) {
    if (region) {
      return `${ctx}تست‌های پیشنهادی برای ناحیه «${region.label}»: ${region.specialTests.join("، ")}. همراه با غربالگری عصبی و تست‌های عملکردی انجام دهید و در بستر کل شرح حال تفسیر کنید.`;
    }
    return `${ctx}تست‌ها را بر اساس ناحیه و فرضیه‌ها انتخاب کنید: غربالگری عصبی، تست‌های اختصاصی مرتبط و تست‌های عملکردی. ناحیه را بگویید تا فهرست اختصاصی بدهم.`;
  }
  if (/tka|knee replacement|post.?op|تعویض مفصل|بعد از جراحی|پس از جراحی/.test(q)) {
    return `${ctx}تمرین‌های ایمن اولیه پس از TKA معمولاً شامل پمپ مچ پا، انقباض چهارسر، سُر دادن پاشنه با کمک برای دامنه خم شدن و Short-arc quads است — همیشه در چارچوب پروتکل جراح و وضعیت تحمل وزن. تورم را با بالا نگه داشتن پا و یخ کنترل کنید و بار را تدریجی افزایش دهید. احتیاط‌ها را با تیم جراحی تأیید کنید.`;
  }
  if (/osteoarthritis|oa\b|knee oa|آرتروز|استئوآرتریت/.test(q)) {
    return `${ctx}در آرتروز زانو، تمرین‌درمانی خط اول است: تقویت چهارسر و لگن، فعالیت هوازی و آموزش. بار را تدریجی افزایش دهید؛ کمی ناراحتی حین تمرین که فروکش کند قابل قبول است. در صورت لزوم مدیریت وزن کمک می‌کند.`;
  }
  if (/progress|پیشرفت/.test(q)) {
    return `${ctx}با قانون پاسخ ۲۴ ساعته پیشرفت دهید: اگر علائم ظرف یک روز فروکش کرد و کنترل خوب است، پیش از حجم، بار یا پیچیدگی را افزایش دهید. ابزارهای سنجش پیامد را هر ۲ تا ۳ هفته دوباره ارزیابی کنید و به سمت هدف عملکردی بیمار پیش بروید.`;
  }
  if (/treatment plan|plan for|برنامه درمان|طرح درمان/.test(q)) {
    return `${ctx}یک برنامه ساختاریافته ترکیبی است از: درمان دستی (مکمل)، تمرین‌درمانی پیشرونده، تحرک، تقویت، کنترل حرکتی، تعادل، آموزش و یک برنامه خانگی متمرکز. شدت را با مرحله و تحریک‌پذیری تطبیق دهید. برای برنامه کامل از «برنامه‌ریز درمان» استفاده کنید.`;
  }
  return `${ctx}می‌توانم در ارزیابی، استدلال بالینی، تست‌ها، برنامه‌ریزی درمان، انتخاب تمرین و پیشرفت کمک کنم. درباره پرچم‌های قرمز، تست‌های مناسب، برنامه درمان یک عارضه یا نحوه پیشرفت بیمار بپرسید. یادتان باشد این فقط پشتیبان تصمیم‌گیری است — یافته‌ها را با معاینه بالینی تأیید کنید.`;
}
