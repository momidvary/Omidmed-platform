/** The region module in the interface language (Arabic falls back to English). */
export function localizeRegion(module: BodyRegionModule, locale: Locale): BodyRegionModule {
  if (locale !== "fa") return module;
  return { ...module, ...bodyRegionsFa[module.id] };
}

export function regionLabel(id: BodyRegionId | null | undefined, locale: Locale): string {
  if (!id) return "";
  const source = getRegion(id);
  if (!source) return id;
  return locale === "fa" ? bodyRegionsFa[id].label : source.label;
}

export function localizedRegions(locale: Locale): BodyRegionModule[] {
  return bodyRegions.map((module) => localizeRegion(module, locale));
}
